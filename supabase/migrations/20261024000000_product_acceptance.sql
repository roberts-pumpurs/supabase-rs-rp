-- Deterministic tables for SDK live acceptance. Existing cron-driven messages are not suitable fixtures.
create extension if not exists pg_graphql with schema graphql;
comment on schema public is '@graphql({"inflect_names": true})';

create table public.graphql_probe (
    id uuid primary key default gen_random_uuid(),
    value text not null
);
alter table public.graphql_probe enable row level security;
grant select, insert, update, delete on public.graphql_probe to anon, authenticated, service_role;
-- No anon/user policy: GraphQL must respect RLS, while service_role can manage acceptance rows.

create table public.product_events (
    id bigint generated by default as identity primary key,
    owner uuid not null default auth.uid() references auth.users(id) on delete cascade,
    message text not null
);
alter table public.product_events enable row level security;
create policy own_events on public.product_events to authenticated
    using (owner = (select auth.uid())) with check (owner = (select auth.uid()));
grant select, insert, update, delete on public.product_events to authenticated, service_role;
grant usage, select on sequence public.product_events_id_seq to authenticated, service_role;
alter publication supabase_realtime add table public.product_events;
